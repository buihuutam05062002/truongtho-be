CREATE TABLE dining_tables
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255),
    position     INTEGER,
    capacity     INTEGER,
    table_status VARCHAR(20),
    CONSTRAINT ck_dining_tables_status
        CHECK (table_status IN ('AVAILABLE', 'MAINTENANCE', 'IN_USE', 'RESERVED', 'SERVING'))
);

CREATE TABLE reservations
(
    reservation_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_code   VARCHAR(255) UNIQUE,
    contact_name       VARCHAR(255),
    contact_phone      VARCHAR(255),
    reservation_time   TIMESTAMP(6),
    party_size         INTEGER,
    note               VARCHAR(500),
    reservation_status VARCHAR(20),
    created_at         TIMESTAMP(6),
    confirmed_by       VARCHAR(36) REFERENCES employees (id),
    table_id           BIGINT REFERENCES dining_tables (id),
    customer_id        VARCHAR(36) REFERENCES customers (id),
    CONSTRAINT ck_reservations_status
        CHECK (reservation_status IN ('PENDING', 'CONFIRMED', 'ARRIVED', 'COMPLETED', 'CANCELLED', 'NO_SHOW'))
);