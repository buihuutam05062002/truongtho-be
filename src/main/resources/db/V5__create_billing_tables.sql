CREATE TABLE voucher
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(255),
    description          VARCHAR(255),
    discount_value       NUMERIC(38, 2),
    discount_value_max   NUMERIC(38, 2),
    minimum_order_amount NUMERIC(38, 2),
    max_quantity         INTEGER,
    used_quantity        INTEGER,
    start                TIMESTAMP(6),
    expire               TIMESTAMP(6),
    created_at           TIMESTAMP(6),
    updated_at           TIMESTAMP(6),
    discount_type        VARCHAR(20),
    voucher_status       VARCHAR(20),
    CONSTRAINT ck_voucher_discount_type CHECK (discount_type IN ('FIXED_AMOUNT', 'PERCENTAGE')),
    CONSTRAINT ck_voucher_status CHECK (voucher_status IN ('DRAFT', 'ACTIVE', 'SUSPENDED', 'INACTIVE'))
);

CREATE TABLE invoices
(
    invoice_id      VARCHAR(36) PRIMARY KEY,
    issued_at       TIMESTAMP(6),
    discount_amount NUMERIC(38, 2),
    total_amount    NUMERIC(38, 2),
    invoice_status  VARCHAR(20),
    points_redeemed INTEGER DEFAULT 0,
    voucher_id      BIGINT REFERENCES voucher (id),
    table_id        BIGINT REFERENCES dining_tables (id),
    reservation_id  BIGINT UNIQUE REFERENCES reservations (reservation_id),
    created_by      VARCHAR(36) REFERENCES employees (id),
    customer_id     VARCHAR(36) REFERENCES customers (id),
    CONSTRAINT ck_invoices_status CHECK (invoice_status IN ('PENDING', 'PAID', 'CANCELLED'))
);

CREATE TABLE invoice_details
(
    invoice_id VARCHAR(36) NOT NULL REFERENCES invoices (invoice_id),
    product_id BIGINT      NOT NULL REFERENCES products (product_id),
    quantity   INTEGER,
    unit_price NUMERIC(38, 2),
    total      NUMERIC(38, 2),
    PRIMARY KEY (invoice_id, product_id)
);

CREATE TABLE payments
(
    id                     VARCHAR(36) PRIMARY KEY,
    amount                 NUMERIC(38, 2),
    transaction_code       VARCHAR(255) NOT NULL UNIQUE,
    payment_status         VARCHAR(20),
    payment_method         VARCHAR(20),
    created_at             TIMESTAMP(6),
    paid_at                TIMESTAMP(6),
    sepay_transaction_id   BIGINT UNIQUE,
    gateway_transaction_id VARCHAR(255) UNIQUE,
    employee_id            VARCHAR(36) REFERENCES employees (id),
    invoice_id             VARCHAR(36)  NOT NULL REFERENCES invoices (invoice_id),
    CONSTRAINT ck_payments_status CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAIL', 'CANCELLED')),
    CONSTRAINT ck_payments_method CHECK (payment_method IN ('ONLINE', 'CASH', 'BANK_TRANSFER'))
);